const fs=require('fs'),path=require('path'),root=__dirname;
const app=fs.readFileSync(path.join(root,'app_v57.js'),'utf8');
const css=fs.readFileSync(path.join(root,'style_v57.css'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'manifest.json'),'utf8'));
const matches=JSON.parse(fs.readFileSync(path.join(root,'data/matches.json'),'utf8')).matches;
const checks=[];const ok=(name,cond,detail='')=>checks.push({name,pass:!!cond,detail});
ok('single nav function',(app.match(/^function nav\(/gm)||[]).length===1);
ok('single render function',(app.match(/^function render\(/gm)||[]).length===1);
ok('escape closes top modal',app.includes("e.key==='Escape'")&&app.includes('closeTopModal()'));
ok('smooth scroll',css.includes('html{scroll-behavior:smooth}'));
ok('focus-visible',css.includes(':focus-visible'));
ok('reduced motion',css.includes('prefers-reduced-motion:reduce'));
ok('favicon linked',html.includes('favicon-64.png')&&fs.existsSync(path.join(root,'favicon-64.png')));
ok('manifest linked',html.includes('manifest.json'));
ok('manifest CS2 identity',manifest.name==='CS2 Analytics'&&manifest.lang==='ru');
ok('CS2 title',html.includes('CS2 Analytics — матчи, карты, игроки'));
ok('new-game still requires 5x5',app.includes('teamA.length!==5||teamB.length!==5'));
ok('historical teams are persisted',matches.every(m=>(m.team_a||[]).length||(m.team_b||[]).length),`${matches.filter(m=>(m.team_a||[]).length||(m.team_b||[]).length).length}/${matches.length}`);
ok('partial historical rosters allowed',matches.every(m=>(m.team_a||[]).length<=5&&(m.team_b||[]).length<=5));
ok('technical partial-data notices removed',!app.includes('Неполная карта: в источнике записано')&&!app.includes('распределение 5×5 не придумывается'));
ok('stability function present',app.includes('function stability('));
ok('map probability uses smoothing',app.includes('smooth=(wins+1)/(played+2)'));
ok('map WR profile present',app.includes('function mapWinRateRows('));
const failed=checks.filter(x=>!x.pass);console.log(JSON.stringify({PASS:failed.length===0,checks},null,2));process.exitCode=failed.length?1:0;
